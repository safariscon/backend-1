const fill = (template, vars = {}) =>
  String(template || "").replace(/\{(\w+)\}/g, (_, key) => (vars[key] == null ? `{${key}}` : String(vars[key])));

const resolveLanguage = (value) => {
  const raw = typeof value === "string" ? value : String(value?.headers?.["x-app-language"] || value?.headers?.["accept-language"] || "en");
  const code = raw.toLowerCase().split(",")[0].split("-")[0].trim();
  return SUPPORTED.includes(code) ? code : "en";
};

const emailCopy = (language) => EMAILS[resolveLanguage(language)] || EMAILS.en;

const greetingName = (copy, name, fallbackKey = "helloThere") => {
  const fallback = copy[fallbackKey] || "";
  const display = String(name || "").trim() || fallback;
  return fill(copy.helloName, { name: display }).replace(/\s+,/, ",").replace("Bonjour ,", "Bonjour,").replace("Habari ,", "Habari,");
};

